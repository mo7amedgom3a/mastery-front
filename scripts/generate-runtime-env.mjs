#!/usr/bin/env node
/**
 * Amplify Hosting injects app environment variables at BUILD time only: the
 * WEB_COMPUTE SSR runtime starts with none of them, so values the server reads
 * at runtime would silently fall back to their development defaults
 * (API_BASE_URL -> localhost, REVALIDATE_SECRET -> undefined, ...).
 *
 * This script runs in the Amplify preBuild phase and snapshots the
 * server-side variables into src/config/runtime-env.ts, which
 * src/instrumentation.ts applies to process.env at server boot, before OTel
 * starts and before any request is served. Client-side values (NEXT_PUBLIC_*)
 * are excluded: Next.js inlines those into the browser bundle at build time on
 * its own, and they must not appear in a server-only module.
 *
 * Local development never runs this script: the committed placeholder module
 * is an empty no-op and .env.local remains the source of truth. If you run it
 * locally, do not commit the generated values (the diff makes that visible).
 */
import { writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const KEYS = [
  "API_BASE_URL",
  "AUTH_COOKIE_SECRET",
  "AUTH_COOKIE_SECURE",
  "REVALIDATE_SECRET",
  "BUNNY_LIBRARY_ID",
  "BUNNY_CDN_HOSTNAME",
  "LMS_COOKIE_DOMAIN",
  "OTEL_SERVICE_NAME",
  "OTEL_SERVICE_VERSION",
  "OTEL_EXPORTER_OTLP_PROTOCOL",
  "OTEL_EXPORTER_OTLP_ENDPOINT",
  "OTEL_EXPORTER_OTLP_HEADERS",
  "OTEL_TRACES_SAMPLER",
  "OTEL_TRACES_SAMPLER_ARG",
];

const captured = {};
for (const key of KEYS) {
  const value = process.env[key];
  if (value !== undefined && value !== "") captured[key] = value;
}

const target = resolve(process.cwd(), "src/config/runtime-env.ts");
const entries = Object.entries(captured)
  .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
  .join("\n");

await mkdir(dirname(target), { recursive: true });
await writeFile(
  target,
  `// Generated by scripts/generate-runtime-env.mjs during the Amplify build — do not edit.
// Applied to process.env in src/instrumentation.ts before any request is served.
export const runtimeEnv: Record<string, string> = {
${entries}
};
`,
);

console.log(`runtime-env.ts: captured ${Object.keys(captured).length} key(s): ${Object.keys(captured).join(", ") || "(none)"}`);
