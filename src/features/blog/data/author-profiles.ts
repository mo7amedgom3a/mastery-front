/**
 * Curated cinematic profiles for the blog's founding authors.
 *
 * The blog post API only carries the instructor summary (name/avatar/bio); the editorial
 * profile content — story, milestones, testimonials, credentials — is curated here from the
 * authors' own material. Pages merge this with the live instructor endpoint (counts, socials)
 * and their published posts, so the profile never drifts from the catalog.
 */

export type AuthorStat = { value: string; label: string };
