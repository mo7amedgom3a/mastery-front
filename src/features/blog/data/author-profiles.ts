  /** URL segment: `/blog/authors/{slug}`. */
  slug: string;
  name: string;
  /** Poster watermark behind the portrait (Latin, poster type). */
  englishName: string;
  title: string;
  tagline: string;
  /** Portrait stage: transparent cutout standing on a solid brand field. */
  portrait: { src: string; alt: string; field: "gold" | "crimson" };
