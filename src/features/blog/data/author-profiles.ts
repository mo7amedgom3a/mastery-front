export function findAuthorProfile(slug: string): AuthorProfile | undefined {
  const normalized = decodeURIComponent(slug).trim().toLowerCase();
  return authorProfiles.find(
    (profile) => profile.slug === normalized || profile.key === normalized,
  );
}

/** The profile for an instructor key, when the author has a curated page. */
export function authorProfileByKey(key: string | null | undefined): AuthorProfile | undefined {
  if (!key) return undefined;
  return authorProfiles.find((profile) => profile.key === key);
}
